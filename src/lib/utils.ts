import renderSizes from "@/components/studio/renders.json";
import clsx, { type ClassValue } from "clsx";

export function cn(...inputs: ClassValue[]) {
  return clsx(inputs);
}

/** Public URL for a media row's path (relative to UPLOAD_DIR). */
export function mediaUrl(relativePath: string): string {
  return `/media/${relativePath.split("/").map(encodeURIComponent).join("/")}`;
}

/**
 * Product picture for a manifest key. Assembled and exploded views use the 3D studio renders
 * (public/renders, served through the image optimiser at a card-friendly width); ortho and flat
 * views stay the static line drawings generated by scripts/illustrations/build.ts.
 */
export function illustrationUrl(key: string, view: "assembled" | "exploded" | "ortho" | "flat" = "assembled", finish?: string) {
  const render = renderName(key, view, finish);
  if (render) return `/_next/image?url=${encodeURIComponent(`/renders/${render}.webp`)}&w=828&q=75`;
  return `/illustrations/${key}-${view}${finish && finish !== "natural" ? `-${finish}` : ""}.svg`;
}

/** The studio render that stands in for an assembled/exploded drawing, if one exists. */
export function renderName(key: string, view: string, finish?: string): string | null {
  if (view !== "assembled" && view !== "exploded") return null;
  const name = view === "exploded" ? `${key}-hero-exploded` : finish === "white" ? `${key}-hero-white` : `${key}-hero`;
  return name in RENDER_SIZES ? name : null;
}

export const RENDER_SIZES = renderSizes as unknown as Record<string, [number, number]>;

/** FNV-1a 32-bit hash — deterministic seeds for grain, tilts, etc. (never Math.random in render). */
export function fnv1a(input: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}
