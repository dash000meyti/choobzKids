/*
 * App icons from the duck-on-cart mark (DESIGN.md §3.6, SEO.md §2 favicon note).
 *
 *   npx tsx scripts/brand/icons.ts
 *
 * Writes (all committed):
 *   src/app/icon.svg        the master: a birch tile with the duck laser-burned into it
 *   src/app/apple-icon.png  180 × 180, full-bleed (iOS masks the corners itself; transparency turns black)
 *   src/app/favicon.ico     16 + 32 px PNG entries
 *   public/icon-192.png     web manifest icons, rounded tile as in the SVG
 *   public/icon-512.png
 *
 * The mark is drawn from Tati's own construction (tati/geometry.ts), so the
 * favicon, the wordmark and the journey duck can never drift apart. It is a
 * bold silhouette on purpose: line art turns to mush at 16 px.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { BEAK, PLATFORM, POSES, WHEELS, WING, duckOutline } from "../../src/components/illustrations/tati/geometry";

const ROOT = path.resolve(import.meta.dirname, "../..");

/* Fixed brand colours (an icon cannot read CSS variables). */
const BIRCH = "#E8D3AE"; // takhte
const HONEY = "#C8955A"; // asal
const WALNUT = "#33251B"; // gerdu
const ANAR = "#B23A26";

const round = (n: number) => Math.round(n * 100) / 100;

function iconSvg(): string {
  const { center: head, tilt } = POSES.waiting.head;
  // Tati's 48 × 40 artboard, scaled and centred on the 48 × 48 tile (≈ 17% margins).
  const place = "translate(6.2 7.6) scale(.8)";
  const wheels = [WHEELS.front, WHEELS.back]
    .map(
      ({ cx, cy }) =>
        `<circle cx="${cx}" cy="${cy}" r="6.3" fill="${WALNUT}" stroke="${BIRCH}" stroke-width="1.5"/>` +
        `<circle cx="${cx}" cy="${cy}" r="2.4" fill="${ANAR}"/>`,
    )
    .join("");

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48">
<!-- Choobz duck-on-cart mark. Generated by scripts/brand/icons.ts from tati/geometry.ts; edit there. -->
<rect width="48" height="48" rx="10.5" fill="${BIRCH}"/>
<path d="M6 13.5c9-1.4 22 .8 36-.6M4.5 30.4c12-1.6 25 .6 39-.8M8 41.5c10-.9 20 .5 32-.4" fill="none" stroke="${HONEY}" stroke-opacity=".28" stroke-width=".6" stroke-linecap="round"/>
<g transform="${place}">
<path d="M3.6 28C1.6 33-.4 37.6-3.6 38.6" fill="none" stroke="${ANAR}" stroke-width="1.6" stroke-linecap="round"/>
<circle cx="-4.6" cy="38.4" r="1.8" fill="${WALNUT}"/>
<path d="${BEAK}" transform="translate(${head[0]} ${head[1]}) rotate(${tilt})" fill="${ANAR}"/>
<path d="${duckOutline(head)}" fill="${WALNUT}"/>
<path d="${WING}" fill="none" stroke="${BIRCH}" stroke-width="1.7" stroke-linecap="round"/>
<circle cx="${round(head[0] - 1.1)}" cy="${round(head[1] - 0.9)}" r="1.9" fill="${BIRCH}"/>
<rect x="${PLATFORM.x}" y="${PLATFORM.y + 0.6}" width="${PLATFORM.width}" height="${PLATFORM.height - 0.6}" rx="1.6" fill="${WALNUT}"/>
${wheels}
</g>
</svg>
`;
}

/** Rasterise at a high density first so small sizes are downsampled, not rendered at 16 px directly. */
function render(svg: Buffer, size: number, background?: string) {
  const image = sharp(svg, { density: 1200 }).resize(size, size, { kernel: "lanczos3" });
  return (background ? image.flatten({ background }) : image).png({ compressionLevel: 9 }).toBuffer();
}

/** Packs PNG images into an .ico container (PNG-in-ICO, supported by every current browser). */
function packIco(images: { size: number; png: Buffer }[]): Buffer {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(images.length, 4);

  const entries: Buffer[] = [];
  let offset = 6 + 16 * images.length;
  for (const { size, png } of images) {
    const entry = Buffer.alloc(16);
    entry.writeUInt8(size >= 256 ? 0 : size, 0); // width
    entry.writeUInt8(size >= 256 ? 0 : size, 1); // height
    entry.writeUInt8(0, 2); // palette size
    entry.writeUInt8(0, 3); // reserved
    entry.writeUInt16LE(1, 4); // colour planes
    entry.writeUInt16LE(32, 6); // bits per pixel
    entry.writeUInt32LE(png.length, 8);
    entry.writeUInt32LE(offset, 12);
    entries.push(entry);
    offset += png.length;
  }
  return Buffer.concat([header, ...entries, ...images.map((i) => i.png)]);
}

async function main() {
  const svgPath = path.join(ROOT, "src/app/icon.svg");
  await writeFile(svgPath, iconSvg());
  const svg = await readFile(svgPath);

  await mkdir(path.join(ROOT, "public"), { recursive: true });
  const outputs: [string, Buffer][] = [
    ["src/app/apple-icon.png", await render(svg, 180, BIRCH)],
    ["public/icon-192.png", await render(svg, 192)],
    ["public/icon-512.png", await render(svg, 512)],
    [
      "src/app/favicon.ico",
      packIco([
        { size: 16, png: await render(svg, 16) },
        { size: 32, png: await render(svg, 32) },
      ]),
    ],
  ];

  for (const [file, data] of outputs) {
    await writeFile(path.join(ROOT, file), data);
    console.log(`${file.padEnd(24)} ${data.length.toLocaleString("en-US")} B`);
  }
  console.log(`${"src/app/icon.svg".padEnd(24)} ${svg.length.toLocaleString("en-US")} B`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
